"""
1일차 실습 ② - 연락처 저장 프로그램

메뉴를 골라 연락처를 추가·조회·검색·삭제하는 간단한 프로그램입니다.
아직 파일에 저장하지는 않습니다. (파일 저장은 4일차에 배웁니다)

사용하는 문법: 리스트 / 딕셔너리 / while / if / 문자열 함수
"""

# 연락처를 담아둘 리스트. 미리 두 명을 넣어 두었습니다.
contacts = [
    {"name": "김철수", "phone": "010-1111-2222", "email": "chulsoo@example.com"},
    {"name": "이영희", "phone": "010-3333-4444", "email": "younghee@example.com"},
]


def show_menu():
    """메뉴를 화면에 보여줍니다."""
    print("\n" + "=" * 34)
    print(" 연락처 관리 프로그램")
    print("=" * 34)
    print(" 1. 연락처 추가")
    print(" 2. 전체 목록 보기")
    print(" 3. 이름으로 검색")
    print(" 4. 연락처 삭제")
    print(" 0. 종료")
    print("=" * 34)


# ---------------------------------------------------------------
# 프로그램 본체
# while True 는 '멈추라고 할 때까지 계속 반복' 이라는 뜻입니다.
# ---------------------------------------------------------------

while True:
    show_menu()
    choice = input("메뉴를 선택하세요: ").strip()

    # -----------------------------------------------------------
    # 1. 추가
    # -----------------------------------------------------------
    if choice == "1":
        name = input("이름: ").strip()

        # 같은 이름이 이미 있는지 확인
        exists = False
        for c in contacts:
            if c["name"] == name:
                exists = True
                break

        if exists:
            print(f"'{name}' 은(는) 이미 등록되어 있습니다.")
            continue   # 아래 코드를 건너뛰고 메뉴로 돌아갑니다

        phone = input("전화번호: ").strip()
        email = input("이메일: ").strip()

        contacts.append({"name": name, "phone": phone, "email": email})
        print(f"'{name}' 을(를) 추가했습니다. (총 {len(contacts)}명)")

    # -----------------------------------------------------------
    # 2. 전체 보기
    # -----------------------------------------------------------
    elif choice == "2":
        if len(contacts) == 0:
            print("등록된 연락처가 없습니다.")
            continue

        print(f"\n총 {len(contacts)}명")
        print("-" * 58)
        print(f"{'번호':^6}{'이름':^10}{'전화번호':^18}{'이메일':<24}")
        print("-" * 58)

        # 이름 가나다순으로 정렬해서 보여줍니다.
        for i, c in enumerate(sorted(contacts, key=lambda x: x["name"]), start=1):
            print(f"{i:^6}{c['name']:^10}{c['phone']:^18}{c['email']:<24}")
        print("-" * 58)

    # -----------------------------------------------------------
    # 3. 검색 - 이름의 일부만 입력해도 찾아 줍니다
    # -----------------------------------------------------------
    elif choice == "3":
        keyword = input("검색할 이름(일부만 입력해도 됩니다): ").strip()

        found = []
        for c in contacts:
            # in 을 쓰면 '포함되어 있는지' 확인할 수 있습니다.
            if keyword in c["name"]:
                found.append(c)

        if len(found) == 0:
            print(f"'{keyword}' 에 해당하는 연락처가 없습니다.")
        else:
            print(f"\n{len(found)}건을 찾았습니다.")
            for c in found:
                print(f"  {c['name']} / {c['phone']} / {c['email']}")

    # -----------------------------------------------------------
    # 4. 삭제
    # -----------------------------------------------------------
    elif choice == "4":
        name = input("삭제할 이름: ").strip()

        target = None
        for c in contacts:
            if c["name"] == name:
                target = c
                break

        if target is None:
            print(f"'{name}' 을(를) 찾을 수 없습니다.")
        else:
            confirm = input(f"'{name}' 을(를) 정말 삭제할까요? (y/n): ").strip().lower()
            if confirm == "y":
                contacts.remove(target)
                print("삭제했습니다.")
            else:
                print("취소했습니다.")

    # -----------------------------------------------------------
    # 0. 종료
    # -----------------------------------------------------------
    elif choice == "0":
        print("프로그램을 종료합니다.")
        break   # while 반복을 빠져나갑니다

    # -----------------------------------------------------------
    # 그 외
    # -----------------------------------------------------------
    else:
        print("0~4 중에서 선택해 주세요.")


