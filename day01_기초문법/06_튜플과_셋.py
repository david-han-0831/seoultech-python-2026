"""
1일차 - 06. 튜플(Tuple)과 집합(Set)

- 튜플: 리스트와 비슷하지만 '한번 만들면 바꿀 수 없는' 묶음
- 집합: 중복이 없고 순서도 없는 묶음
"""

# ===============================================================
# 1부. 튜플 (Tuple)
# ===============================================================

# ---------------------------------------------------------------
# 1. 튜플 만들기
# ---------------------------------------------------------------

point = (3, 5)                 # 소괄호로 만듭니다
colors = ("빨강", "초록", "파랑")
single = (1,)                  # 값이 하나면 쉼표를 꼭 붙여야 합니다!
not_tuple = (1)                # 이건 그냥 숫자 1 입니다

print(type(single))      # <class 'tuple'>
print(type(not_tuple))   # <class 'int'>

# 소괄호는 생략할 수도 있습니다.
coords = 10, 20
print(coords, type(coords))


# ---------------------------------------------------------------
# 2. 리스트와 같은 점 / 다른 점
# ---------------------------------------------------------------

colors = ("빨강", "초록", "파랑")

# 같은 점 : 인덱싱, 슬라이싱, 순회, len, in 모두 됩니다.
print(colors[0])      # 빨강
print(colors[-1])     # 파랑
print(colors[1:])     # ('초록', '파랑')
print(len(colors))    # 3
print("초록" in colors)  # True

for c in colors:
    print(c, end=" ")
print()

# 다른 점 : 값을 바꿀 수 없습니다.
# colors[0] = "노랑"     # TypeError
# colors.append("노랑")  # AttributeError


# ---------------------------------------------------------------
# 3. 튜플은 왜 쓸까?
# ---------------------------------------------------------------

# 3-1. 바뀌면 안 되는 값을 실수로부터 보호합니다.
WEEKDAYS = ("월", "화", "수", "목", "금")
MENU_PRICE = ("아메리카노", 4500)

# 3-2. 함수가 여러 값을 돌려줄 때 자동으로 튜플이 됩니다.
def min_max(numbers):
    return min(numbers), max(numbers)   # 사실은 튜플을 돌려주는 것

result = min_max([3, 9, 1, 7])
print(result)         # (1, 9)
print(type(result))   # <class 'tuple'>

# 언패킹(unpacking) : 튜플을 낱개 변수로 풀어 받기
low, high = min_max([3, 9, 1, 7])
print(low, high)      # 1 9

# 3-3. 딕셔너리의 키로 쓸 수 있습니다. (리스트는 불가능)
location = {(37.5, 127.0): "서울", (35.1, 129.0): "부산"}
print(location[(37.5, 127.0)])


# ---------------------------------------------------------------
# 4. 튜플 ↔ 리스트 변환
# ---------------------------------------------------------------

t = (1, 2, 3)
lst = list(t)      # 튜플 → 리스트
lst.append(4)
t2 = tuple(lst)    # 리스트 → 튜플
print(t2)          # (1, 2, 3, 4)


# ===============================================================
# 2부. 집합 (Set)
# ===============================================================

# ---------------------------------------------------------------
# 5. 집합 만들기
# ---------------------------------------------------------------

s = {1, 2, 3, 3, 3}     # 중괄호로 만듭니다. 중복은 자동으로 사라집니다.
print(s)                # {1, 2, 3}

empty_set = set()       # 빈 집합은 set() 으로! {} 는 빈 딕셔너리입니다.
print(type({}))         # <class 'dict'>
print(type(set()))      # <class 'set'>

# 집합은 순서가 없습니다. 인덱싱이 안 됩니다.
# print(s[0])   # TypeError


# ---------------------------------------------------------------
# 6. 집합의 가장 흔한 용도 - 중복 제거
# ---------------------------------------------------------------

visitors = ["김철수", "이영희", "김철수", "박민수", "이영희"]
unique_visitors = set(visitors)
print(unique_visitors)              # 중복 제거됨
print(len(unique_visitors))         # 3   순 방문자 수
print(list(unique_visitors))        # 다시 리스트로


# ---------------------------------------------------------------
# 7. 집합 연산 - 교집합, 합집합, 차집합
# ---------------------------------------------------------------

a = {1, 2, 3, 4, 5}
b = {4, 5, 6, 7}

print(a & b)   # {4, 5}                 교집합 (a.intersection(b))
print(a | b)   # {1,2,3,4,5,6,7}        합집합 (a.union(b))
print(a - b)   # {1, 2, 3}              차집합 (a.difference(b))
print(a ^ b)   # {1,2,3,6,7}            대칭차집합 (한쪽에만 있는 것)

# 실전 예: 두 강의를 모두 수강한 학생 찾기
python_class = {"김철수", "이영희", "박민수"}
java_class = {"이영희", "박민수", "최지우"}
print("둘 다 수강:", python_class & java_class)
print("파이썬만 수강:", python_class - java_class)


# ---------------------------------------------------------------
# 8. 집합의 추가·삭제
# ---------------------------------------------------------------

s = {1, 2, 3}
s.add(4)          # 하나 추가
s.update([5, 6])  # 여러 개 추가
s.discard(1)      # 삭제 (없어도 에러 안 남)
s.remove(2)       # 삭제 (없으면 에러)
print(s)


# ---------------------------------------------------------------
# 9. 리스트 / 튜플 / 집합 비교 정리
# ---------------------------------------------------------------
#
#            리스트 []      튜플 ()        집합 {}
# 순서        있음           있음           없음
# 수정        가능           불가능          가능(원소 추가/삭제)
# 중복        허용           허용           불가
# 인덱싱      가능           가능           불가
# 주 용도     일반적인 목록   고정된 묶음     중복 제거, 포함 검사
#
# [속도 팁] "이 값이 안에 있나?" 를 자주 물어봐야 한다면
#          리스트보다 집합이 훨씬 빠릅니다.


