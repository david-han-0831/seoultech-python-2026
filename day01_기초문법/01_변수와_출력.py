"""
1일차 - 01. 변수와 출력

변수는 '값에 붙이는 이름표'입니다.
값을 어딘가에 담아두고 나중에 그 이름으로 꺼내 쓰기 위해 사용합니다.
"""

# ---------------------------------------------------------------
# 1. 변수 만들기
# ---------------------------------------------------------------

# 왼쪽에 이름, 가운데 = , 오른쪽에 값을 씁니다.
# = 는 '같다'가 아니라 '오른쪽 값을 왼쪽 이름에 넣어라'는 뜻입니다.
name = "한동윤"
age = 20
height = 175.5
is_student = True

print(name)
print(age)
print(height)
print(is_student)


# ---------------------------------------------------------------
# 2. 변수는 언제든 다시 바꿀 수 있습니다
# ---------------------------------------------------------------

score = 80
print(score)  # 80

score = 95  # 새 값으로 덮어쓰기
print(score)  # 95

score = score + 5  # 자기 자신을 이용해 갱신
print(score)  # 100

# 위 문장은 아래처럼 짧게 쓸 수도 있습니다. (복합 대입 연산자)
score += 10   # score = score + 10
score -= 20   # score = score - 20
score *= 2    # score = score * 2
print(score)  # 180


# ---------------------------------------------------------------
# 3. 변수 이름 규칙
# ---------------------------------------------------------------

# [가능]
student_name = "김철수"   # 소문자 + 밑줄 (파이썬 권장 스타일)
score2 = 90              # 숫자는 뒤에 올 수 있음
_temp = 1                # 밑줄로 시작 가능

# [불가능] - 아래 줄들의 주석을 풀면 에러가 납니다.
# 2score = 90     # 숫자로 시작할 수 없음
# student-name = 1  # 하이픈(-)은 뺄셈 기호라 쓸 수 없음
# class = "A"     # class 는 파이썬이 이미 쓰고 있는 예약어

# [주의] 대소문자를 구분합니다. name 과 Name 은 서로 다른 변수입니다.
Name = "다른 사람"
print(name)  # 한동윤
print(Name)  # 다른 사람


# ---------------------------------------------------------------
# 4. print() 여러 가지 사용법
# ---------------------------------------------------------------

# 4-1. 쉼표로 여러 값을 한 번에 출력 (자동으로 공백 한 칸이 들어감)
print("이름:", name, "나이:", age)

# 4-2. sep - 값 사이에 넣을 문자를 바꿉니다
print("2026", "08", "03", sep="-")   # 2026-08-03
print("a", "b", "c", sep="")         # abc

# 4-3. end - 출력 끝에 붙일 문자를 바꿉니다 (기본값은 줄바꿈 "\n")
print("줄바꿈 없이", end=" ")
print("이어서 출력됩니다")

# 4-4. 문자열 + 문자열 은 이어붙이기입니다
print("안녕하세요, " + name + "님")

# [주의] 문자열 + 숫자 는 에러입니다. 타입이 달라서 더할 수 없습니다.
# print("나이: " + age)   # TypeError
print("나이: " + str(age))  # str() 로 숫자를 문자열로 바꾸면 됩니다


# ---------------------------------------------------------------
# 5. f-string : 가장 많이 쓰는 출력 방식
# ---------------------------------------------------------------

# 따옴표 앞에 f 를 붙이고, 중괄호 { } 안에 변수를 넣습니다.
print(f"{name}님은 {age}살이고 키는 {height}cm 입니다.")

# 중괄호 안에서 계산도 됩니다.
print(f"내년이면 {age + 1}살이 됩니다.")

# 소수점 자리수 지정 : {값:.자리수f}
pi = 3.141592653589793
print(f"원주율은 대략 {pi:.2f} 입니다.")   # 3.14
print(f"원주율은 대략 {pi:.4f} 입니다.")   # 3.1416

# 천 단위 쉼표 : {값:,}
salary = 32500000
print(f"연봉은 {salary:,}원 입니다.")      # 32,500,000원

# 자리 맞추기 : < 왼쪽정렬, > 오른쪽정렬, ^ 가운데정렬
print(f"|{'이름':<10}|{'점수':>5}|")
print(f"|{'김철수':<10}|{95:>5}|")
print(f"|{'이영희':<10}|{100:>5}|")


# ---------------------------------------------------------------
# 6. 여러 변수를 한 줄에
# ---------------------------------------------------------------

x, y, z = 1, 2, 3
print(x, y, z)

# 값 교환(swap) - 다른 언어에서는 임시 변수가 필요하지만 파이썬은 한 줄이면 됩니다.
a, b = 10, 20
a, b = b, a
print(a, b)  # 20 10

# 같은 값을 여러 변수에
p = q = r = 0
print(p, q, r)


