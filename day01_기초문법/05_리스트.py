"""
1일차 - 05. 리스트 (List)

리스트는 여러 값을 '순서대로' 담는 그릇입니다.
대괄호 [ ] 로 만들고, 값을 자유롭게 추가·삭제·수정할 수 있습니다.
"""

# ---------------------------------------------------------------
# 1. 리스트 만들기
# ---------------------------------------------------------------

numbers = [1, 2, 3, 4, 5]
fruits = ["사과", "바나나", "포도"]
empty = []                                # 빈 리스트
mixed = [1, "글자", 3.14, True]            # 서로 다른 자료형도 함께 담을 수 있음

print(numbers)
print(fruits)
print(len(fruits))  # 3   개수 세기


# ---------------------------------------------------------------
# 2. 인덱싱과 슬라이싱 (문자열과 규칙이 똑같습니다)
# ---------------------------------------------------------------

fruits = ["사과", "바나나", "포도", "딸기", "수박"]
#           0        1        2       3       4
#          -5       -4       -3      -2      -1

print(fruits[0])     # 사과
print(fruits[-1])    # 수박
print(fruits[1:3])   # ['바나나', '포도']
print(fruits[:2])    # ['사과', '바나나']
print(fruits[2:])    # ['포도', '딸기', '수박']
print(fruits[::-1])  # 거꾸로

# 문자열과 달리 리스트는 값을 바꿀 수 있습니다. (가변)
fruits[0] = "청사과"
print(fruits)


# ---------------------------------------------------------------
# 3. 값 추가하기
# ---------------------------------------------------------------

items = []

items.append("첫번째")          # 맨 뒤에 하나 추가
items.append("두번째")
print(items)

items.insert(0, "맨앞")         # 원하는 위치에 끼워넣기
print(items)

items.extend(["세번째", "네번째"])  # 여러 개를 한 번에 이어붙이기
print(items)

# [주의] append 와 extend 의 차이
a = [1, 2]
a.append([3, 4])
print(a)   # [1, 2, [3, 4]]   ← 리스트 통째로 하나의 값이 됨

b = [1, 2]
b.extend([3, 4])
print(b)   # [1, 2, 3, 4]     ← 낱개로 풀려서 들어감

# + 연산자로도 이어붙일 수 있습니다.
print([1, 2] + [3, 4])   # [1, 2, 3, 4]
print([0] * 5)           # [0, 0, 0, 0, 0]   초기화할 때 자주 씁니다


# ---------------------------------------------------------------
# 4. 값 삭제하기
# ---------------------------------------------------------------

nums = [10, 20, 30, 40, 50, 30]

nums.remove(30)     # '값'으로 삭제 (맨 앞에 있는 것 하나만)
print(nums)         # [10, 20, 40, 50, 30]

last = nums.pop()   # 맨 뒤 값을 꺼내면서 삭제 (꺼낸 값을 돌려줌)
print(last, nums)   # 30 [10, 20, 40, 50]

first = nums.pop(0)  # 위치를 지정해 꺼내기
print(first, nums)   # 10 [20, 40, 50]

del nums[0]         # 위치로 삭제
print(nums)         # [40, 50]

nums.clear()        # 전부 비우기
print(nums)         # []


# ---------------------------------------------------------------
# 5. 검색과 정렬
# ---------------------------------------------------------------

scores = [88, 95, 70, 100, 62]

print(95 in scores)          # True   포함 여부
print(scores.index(70))      # 2      위치 찾기
print(scores.count(88))      # 1      개수 세기

print(max(scores))           # 100
print(min(scores))           # 62
print(sum(scores))           # 415
print(sum(scores) / len(scores))  # 83.0  평균

# sort() : 원본을 직접 정렬 (돌려주는 값이 없음!)
scores.sort()
print(scores)                # [62, 70, 88, 95, 100]

scores.sort(reverse=True)    # 내림차순
print(scores)                # [100, 95, 88, 70, 62]

# sorted() : 원본은 그대로 두고 '정렬된 새 리스트'를 돌려줌
original = [3, 1, 2]
new_list = sorted(original)
print(original, new_list)    # [3, 1, 2] [1, 2, 3]

scores.reverse()             # 순서 뒤집기 (정렬이 아님)
print(scores)


# ---------------------------------------------------------------
# 6. 리스트 복사 - 아주 중요한 함정
# ---------------------------------------------------------------

a = [1, 2, 3]
b = a          # 이건 복사가 아니라 '같은 리스트에 이름표 하나 더 붙이기'
b.append(4)
print(a)       # [1, 2, 3, 4]   ← a 도 같이 바뀝니다!

# 진짜 복사하려면
a = [1, 2, 3]
b = a.copy()   # 또는 b = a[:]  또는 b = list(a)
b.append(4)
print(a, b)    # [1, 2, 3] [1, 2, 3, 4]


# ---------------------------------------------------------------
# 7. 리스트 순회
# ---------------------------------------------------------------

fruits = ["사과", "바나나", "포도"]

# 값만 필요할 때
for fruit in fruits:
    print(fruit)

# 순번도 함께 필요할 때 → enumerate
for i, fruit in enumerate(fruits):
    print(f"{i}번: {fruit}")

# 1번부터 세고 싶다면
for i, fruit in enumerate(fruits, start=1):
    print(f"{i}번: {fruit}")

# 두 리스트를 짝지어 볼 때 → zip
names = ["김철수", "이영희", "박민수"]
scores = [90, 85, 77]
for name, score in zip(names, scores):
    print(f"{name}: {score}점")


