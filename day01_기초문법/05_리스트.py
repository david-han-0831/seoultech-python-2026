# 8. 실전 예제
# ---------------------------------------------------------------

# 8-1. 평균 이상인 점수만 뽑기
scores = [88, 95, 70, 100, 62, 45, 91]
average = sum(scores) / len(scores)
above = []
for s in scores:
    if s >= average:
        above.append(s)
print(f"평균 {average:.1f}점 이상: {above}")

# 8-2. 중복 제거 (set 을 거치면 간단합니다. 단, 순서는 보장되지 않습니다)
duplicated = [1, 2, 2, 3, 3, 3, 4]
print(list(set(duplicated)))   # [1, 2, 3, 4]

# 순서를 유지하며 중복 제거
unique = []
for n in duplicated:
    if n not in unique:
        unique.append(n)
print(unique)

# 8-3. 상위 3개만
scores = [88, 95, 70, 100, 62, 45, 91]
top3 = sorted(scores, reverse=True)[:3]
print("상위 3개:", top3)


