# ---------------------------------------------------------------
# 1. 문자열 만들기
# ---------------------------------------------------------------

s1 = "큰따옴표"
s2 = '작은따옴표'      # 둘 다 똑같습니다
s3 = """여러 줄을
그대로 담고 싶을 때는
따옴표 세 개를 씁니다."""

print(s1, s2)
print(s3)

# 따옴표 안에 따옴표를 넣고 싶다면
print("그는 '안녕'이라고 말했다")
print('그는 "안녕"이라고 말했다')
print("그는 \"안녕\"이라고 말했다")  # 역슬래시로 escape


# ---------------------------------------------------------------
# 2. 특수 문자 (escape sequence)
# ---------------------------------------------------------------

print("줄바꿈:\n다음 줄")
print("탭:\t띄어쓰기")
print("역슬래시 자체:\\")

# 윈도우 경로처럼 역슬래시가 많으면 앞에 r 을 붙입니다. (raw string)
print(r"C:\Users\name\Documents")


# ---------------------------------------------------------------
# 3. 인덱싱 - 몇 번째 글자 꺼내기
# ---------------------------------------------------------------

text = "Python"
#       012345      ← 앞에서 셀 때 (0부터 시작!)
#      -654321      ← 뒤에서 셀 때 (-1부터 시작)

print(text[0])   # P   첫 글자
print(text[3])   # h
print(text[-1])  # n   마지막 글자
print(text[-2])  # o

# 없는 위치를 부르면 에러입니다.
# print(text[10])  # IndexError

# 문자열은 '불변'이라 이렇게 바꿀 수 없습니다.
# text[0] = "J"   # TypeError
# 새로 만들어야 합니다.
text2 = "J" + text[1:]
print(text2)  # Jython


# ---------------------------------------------------------------
# 4. 슬라이싱 - 잘라내기  [시작:끝:간격]
# ---------------------------------------------------------------

text = "Hello, Python!"

print(text[0:5])    # Hello   0번부터 5번 '앞'까지 (끝 번호는 포함 안 됨)
print(text[7:13])   # Python
print(text[:5])     # Hello   시작 생략 = 처음부터
print(text[7:])     # Python! 끝 생략   = 마지막까지
print(text[:])      # 전체 복사
print(text[::2])    # Hlo yhn  두 칸씩 건너뛰기
print(text[::-1])   # !nohtyP ,olleH  거꾸로 뒤집기 (자주 쓰는 관용구)

# 뒤에서 3글자
print(text[-3:])    # on!


# ---------------------------------------------------------------
# 5. 자주 쓰는 문자열 함수
# ---------------------------------------------------------------

s = "  Hello Python World  "

print(s.strip())            # 앞뒤 공백 제거 → "Hello Python World"
print(s.lstrip())           # 왼쪽만
print(s.rstrip())           # 오른쪽만

print("abc".upper())        # ABC     대문자로
print("ABC".lower())        # abc     소문자로
print("hello world".title())  # Hello World  각 단어 첫 글자 대문자

print("apple".replace("p", "b"))   # abble   바꾸기
print("a,b,c".split(","))          # ['a', 'b', 'c']  자르기
print("-".join(["2026", "08", "03"]))  # 2026-08-03   합치기

print("Python".find("th"))     # 2    찾은 위치 (없으면 -1)
print("Python".index("th"))    # 2    찾은 위치 (없으면 에러)
print("banana".count("a"))     # 3    개수 세기

print("Python".startswith("Py"))  # True
print("test.py".endswith(".py"))  # True

print("hello" in "hello world")   # True   포함 여부 확인 (가장 간편)
print("bye" not in "hello world") # True


# ---------------------------------------------------------------
# 6. 문자열 판별 함수
# ---------------------------------------------------------------

print("12345".isdigit())   # True   숫자로만 되어 있는가
print("abc".isalpha())     # True   글자로만 되어 있는가
print("abc123".isalnum())  # True   글자+숫자인가
print("   ".isspace())     # True   공백뿐인가
print("Hello".islower())   # False


# ---------------------------------------------------------------
# 7. 문자열 * 숫자 = 반복
# ---------------------------------------------------------------

print("=" * 40)
print("파이썬 특강")
print("=" * 40)
print("-" * 10 + " 구분선 " + "-" * 10)


# ---------------------------------------------------------------
# 8. 문자열 순회
# ---------------------------------------------------------------

for char in "Python":
    print(char, end=" ")
