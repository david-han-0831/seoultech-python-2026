"""
1일차 - 02. 입력받기

input() 은 사용자가 키보드로 친 값을 프로그램 안으로 가져옵니다.
가장 중요한 규칙 한 가지: input() 의 결과는 '언제나 문자열'입니다.
"""

# ---------------------------------------------------------------
# 1. 가장 기본
# ---------------------------------------------------------------

name = input("이름을 입력하세요: ")
print(f"안녕하세요, {name}님!")


# ---------------------------------------------------------------
# 2. input() 은 무조건 문자열을 돌려줍니다
# ---------------------------------------------------------------

age = input("나이를 입력하세요: ")
print(type(age))  # <class 'str'>  ← 숫자를 입력해도 문자열입니다

# 그래서 이렇게 하면 원하는 결과가 안 나옵니다.
print(age + age)  # "20" + "20" → "2020" (덧셈이 아니라 이어붙이기)

# 숫자로 계산하려면 int() 나 float() 로 바꿔야 합니다.
age_number = int(age)
print(age_number + 1)  # 21

# 입력받으면서 바로 변환하는 것이 일반적입니다.
height = float(input("키를 입력하세요(cm): "))
print(f"내년에 1cm 자라면 {height + 1}cm 입니다.")


# ---------------------------------------------------------------
# 3. 자주 만나는 에러
# ---------------------------------------------------------------

# int("스물") 처럼 숫자가 아닌 값을 넣으면 ValueError 가 납니다.
# 아래 주석을 풀고 "abc" 를 입력해 보세요.
# num = int(input("숫자를 입력하세요: "))

# 실무에서는 이렇게 방어합니다. (예외처리는 4일차에 자세히 다룹니다)
raw = input("숫자를 입력하세요: ")
if raw.isdigit():           # 문자열이 숫자로만 이루어져 있는지 확인
    print(f"입력한 수의 두 배는 {int(raw) * 2} 입니다.")
else:
    print("숫자가 아닙니다.")


# ---------------------------------------------------------------
# 4. 한 줄에 여러 값 입력받기
# ---------------------------------------------------------------

# split() 은 문자열을 공백 기준으로 잘라 리스트로 만듭니다.
# 예) "10 20" → ["10", "20"]
a, b = input("두 숫자를 공백으로 구분해 입력하세요: ").split()
a = int(a)
b = int(b)
print(f"{a} + {b} = {a + b}")

# map() 을 쓰면 잘라낸 조각을 한 번에 int 로 바꿀 수 있습니다.
x, y = map(int, input("두 숫자를 다시 입력하세요: ").split())
print(f"{x} * {y} = {x * y}")

# 개수가 정해지지 않았다면 리스트로 받습니다.
numbers = list(map(int, input("숫자를 여러 개 입력하세요: ").split()))
print("입력한 값들:", numbers)
print("합계:", sum(numbers))

# 쉼표로 구분해 입력받고 싶다면 split(",") 처럼 기준을 지정합니다.
fruits = input("과일을 쉼표로 구분해 입력하세요: ").split(",")
print(fruits)


# ---------------------------------------------------------------
# 5. 입력값 다듬기
# ---------------------------------------------------------------

# strip() : 앞뒤 공백 제거. 사용자가 실수로 띄어쓰기를 넣는 경우가 많습니다.
city = input("도시 이름을 입력하세요: ").strip()
print(f"[{city}]")

# lower() / upper() : 대소문자 통일. 답변 비교할 때 유용합니다.
answer = input("계속하시겠습니까? (Y/N): ").strip().lower()
if answer == "y":
    print("계속합니다.")
else:
    print("종료합니다.")


