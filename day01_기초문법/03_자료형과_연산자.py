"""
1일차 - 03. 자료형과 연산자

자료형(data type)은 '값의 종류'입니다.
같은 3이라도 숫자 3과 문자 "3"은 컴퓨터에게 전혀 다른 값입니다.
"""

# ---------------------------------------------------------------
# 1. 기본 자료형 네 가지
# ---------------------------------------------------------------

count = 10           # int   : 정수
price = 3.14         # float : 실수(소수점)
title = "파이썬"      # str   : 문자열
is_open = True       # bool  : 참/거짓 (True 또는 False, 첫 글자 대문자!)

# type() 으로 자료형을 확인할 수 있습니다.
print(type(count))    # <class 'int'>
print(type(price))    # <class 'float'>
print(type(title))    # <class 'str'>
print(type(is_open))  # <class 'bool'>


# ---------------------------------------------------------------
# 2. 형변환 (casting)
# ---------------------------------------------------------------

print(int("100"))      # 문자열 → 정수 : 100
print(int(3.9))        # 실수 → 정수   : 3   (반올림이 아니라 소수점 버림!)
print(float("3.5"))    # 문자열 → 실수 : 3.5
print(str(100))        # 숫자 → 문자열 : "100"
print(bool(0))         # 0은 False
print(bool(1))         # 0이 아닌 수는 True
print(bool(""))        # 빈 문자열은 False
print(bool("아무거나"))  # 내용이 있으면 True

# [주의] 소수점이 있는 문자열은 int() 로 바로 못 바꿉니다.
# print(int("3.5"))    # ValueError
print(int(float("3.5")))  # float 을 거치면 됩니다 → 3


# ---------------------------------------------------------------
# 3. 산술 연산자
# ---------------------------------------------------------------

a = 17
b = 5

print(a + b)   # 22   더하기
print(a - b)   # 12   빼기
print(a * b)   # 85   곱하기
print(a / b)   # 3.4  나누기 → 결과는 항상 실수(float)
print(a // b)  # 3    몫    (소수점 버림)
print(a % b)   # 2    나머지
print(a ** b)  # 1419857  거듭제곱 (17의 5제곱)

# % (나머지)는 생각보다 자주 씁니다.
number = 7
if number % 2 == 0:
    print("짝수")
else:
    print("홀수")

# // (몫)의 활용 : 초를 분/초로 나누기
total_seconds = 195
print(f"{total_seconds}초는 {total_seconds // 60}분 {total_seconds % 60}초 입니다.")


# ---------------------------------------------------------------
# 4. 비교 연산자 - 결과는 항상 True 또는 False
# ---------------------------------------------------------------

print(10 == 10)   # True   같다 ( = 하나는 '대입', == 두 개가 '비교')
print(10 != 3)    # True   다르다
print(10 > 3)     # True
print(10 < 3)     # False
print(10 >= 10)   # True
print(10 <= 9)    # False

# 문자열도 비교할 수 있습니다. (사전 순서 기준)
print("apple" == "apple")  # True
print("apple" < "banana")  # True  (a가 b보다 앞)

# 파이썬은 범위 비교를 이어 쓸 수 있습니다. 다른 언어에는 없는 편의 기능입니다.
score = 85
print(80 <= score < 90)  # True


# ---------------------------------------------------------------
# 5. 논리 연산자 - and / or / not
# ---------------------------------------------------------------

age = 25
has_ticket = True

print(age >= 20 and has_ticket)   # 둘 다 참이어야 True
print(age >= 65 or has_ticket)    # 하나만 참이어도 True
print(not has_ticket)             # 참/거짓 뒤집기 → False

# 실제로는 이렇게 조합해 씁니다.
temperature = 28
is_raining = False

if temperature > 25 and not is_raining:
    print("산책하기 좋은 날씨입니다.")


# ---------------------------------------------------------------
# 6. 실수 계산의 함정
# ---------------------------------------------------------------

# 컴퓨터는 소수를 2진수로 저장하기 때문에 아주 작은 오차가 생깁니다.
print(0.1 + 0.2)             # 0.30000000000000004
print(0.1 + 0.2 == 0.3)      # False !!

# 해결 방법 1: round() 로 자리수를 맞춰 비교
print(round(0.1 + 0.2, 10) == 0.3)  # True

# 해결 방법 2: 돈 계산처럼 정확도가 중요하면 decimal 모듈 사용
from decimal import Decimal
print(Decimal("0.1") + Decimal("0.2") == Decimal("0.3"))  # True


# ---------------------------------------------------------------
# 7. 자주 쓰는 내장 함수
# ---------------------------------------------------------------

print(abs(-7))          # 7      절댓값
print(round(3.567, 1))  # 3.6    반올림
print(max(3, 9, 1))     # 9      최댓값
print(min(3, 9, 1))     # 1      최솟값
print(sum([1, 2, 3]))   # 6      합계
print(len("파이썬"))     # 3      길이
print(pow(2, 10))       # 1024   거듭제곱 (2 ** 10 과 같음)


