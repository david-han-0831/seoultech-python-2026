// ---------------------------------------------------------------
// 1. for 문 - 자바스크립트의 기본 형태
// ---------------------------------------------------------------

// 파이썬:  for i in range(5):
// 자바스크립트는 세 부분을 직접 씁니다.
//
//   for (시작값; 계속조건; 증감) { ... }
//        ①       ②        ③

for (let i = 0; i < 5; i++) {
  console.log(i);   // 0 1 2 3 4
}

// 동작 순서:
//   ① let i = 0   딱 한 번 실행
//   ② i < 5       매 반복 전에 검사 → false 면 종료
//   ③ i++         한 바퀴 끝날 때마다 실행

// 1부터 10까지
for (let i = 1; i <= 10; i++) {
  process.stdout.write(i + " ");   // 줄바꿈 없이 출력 (Node.js 전용)
}
console.log();   // 줄바꿈

// 거꾸로
for (let i = 5; i > 0; i--) {
  process.stdout.write(i + " ");   // 5 4 3 2 1
}
console.log();

// 2씩 건너뛰기 (파이썬 range(0, 10, 2))
for (let i = 0; i < 10; i += 2) {
  process.stdout.write(i + " ");   // 0 2 4 6 8
}
console.log();


// ---------------------------------------------------------------
// 2. for...of - 파이썬의 for x in 리스트 와 같음
// ---------------------------------------------------------------

const fruits = ["사과", "바나나", "포도"];

for (const fruit of fruits) {
  console.log(fruit);
}

// 값만 필요할 때는 이게 훨씬 읽기 좋습니다. 실무에서 제일 많이 씁니다.

// 인덱스도 같이 필요하면 entries() 를 씁니다. (파이썬 enumerate)
for (const [index, fruit] of fruits.entries()) {
  console.log(`${index}번: ${fruit}`);
}


// ---------------------------------------------------------------
// 3. for...in - 객체의 키를 돕니다 (배열에는 쓰지 마세요)
// ---------------------------------------------------------------

const student = { name: "홍길동", age: 20, major: "ITM" };

for (const key in student) {
  console.log(`${key} = ${student[key]}`);
}

// [주의] for...of 와 for...in 은 이름이 비슷하지만 완전히 다릅니다.
//   of → 값   (배열용)
//   in → 키   (객체용)


// ---------------------------------------------------------------
// 4. while
// ---------------------------------------------------------------

let count = 0;

while (count < 3) {
  console.log(`count = ${count}`);
  count++;      // ← 이걸 빼먹으면 무한 루프입니다. 반드시 확인하세요.
}

// 무한 루프에 빠졌다면 터미널에서 Ctrl + C 로 강제 종료합니다.


// ---------------------------------------------------------------
// 5. break 와 continue - 파이썬과 동일
// ---------------------------------------------------------------

for (let i = 1; i <= 10; i++) {
  if (i === 5) break;        // 5에서 반복 자체를 끝냄
  process.stdout.write(i + " ");   // 1 2 3 4
}
console.log();

for (let i = 1; i <= 10; i++) {
  if (i % 2 === 0) continue; // 짝수면 건너뛰고 다음 반복으로
  process.stdout.write(i + " ");   // 1 3 5 7 9
}
console.log();


// ---------------------------------------------------------------
// 6. 중첩 반복문 - 구구단
// ---------------------------------------------------------------

for (let dan = 2; dan <= 4; dan++) {
  console.log(`--- ${dan}단 ---`);
  for (let i = 1; i <= 9; i++) {
    console.log(`${dan} x ${i} = ${dan * i}`);
  }
}


// ---------------------------------------------------------------
// 7. forEach - 배열 전용 반복 (자바스크립트다운 방식)
// ---------------------------------------------------------------

// 배열의 각 요소에 대해 함수를 실행합니다. 다음 파일에서 자세히 봅니다.

fruits.forEach(function (fruit, index) {
  console.log(`${index}: ${fruit}`);
});

// 화살표 함수로 짧게 (요즘 스타일)
fruits.forEach((fruit, index) => {
  console.log(`${index}: ${fruit}`);
});

// [주의] forEach 안에서는 break / continue 를 쓸 수 없습니다.
//        중간에 멈춰야 하면 일반 for 문이나 for...of 를 쓰세요.


