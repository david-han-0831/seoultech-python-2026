// ---------------------------------------------------------------
// 1. 산술 연산자 - 파이썬과 거의 같습니다
// ---------------------------------------------------------------

console.log(10 + 3);   // 13
console.log(10 - 3);   // 7
console.log(10 * 3);   // 30
console.log(10 / 3);   // 3.3333...  ← 파이썬과 같음
console.log(10 % 3);   // 1          나머지
console.log(10 ** 3);  // 1000       거듭제곱

// [주의] 파이썬의 // (몫) 은 자바스크립트에 없습니다.
console.log(Math.floor(10 / 3));  // 3  ← 이렇게 씁니다

// 증가/감소
let count = 0;
count += 1;   // count = count + 1
count++;      // 이것도 +1 (파이썬에는 없는 문법)
console.log(count);  // 2


// ---------------------------------------------------------------
// 2. 비교 연산자 - === 를 씁니다 (가장 중요)
// ---------------------------------------------------------------

console.log(10 > 3);    // true
console.log(10 <= 3);   // false

// 같음 비교는 = 이 3개입니다.
console.log(10 === 10);   // true
console.log(10 !== 3);    // true

// [매우 중요] == 와 === 의 차이
console.log(1 == "1");    // true   ← 타입을 멋대로 맞춰서 비교 (느슨한 비교)
console.log(1 === "1");   // false  ← 타입까지 비교 (엄격한 비교)

console.log(0 == false);   // true   ← 이런 게 버그의 원인이 됩니다
console.log(0 === false);  // false

// 규칙: 항상 === 와 !== 만 쓰세요. == 는 쓰지 않습니다.


// ---------------------------------------------------------------
// 3. 논리 연산자
// ---------------------------------------------------------------

//   Python    JavaScript
//   and   →   &&
//   or    →   ||
//   not   →   !

const age = 20;
const hasTicket = true;

console.log(age >= 19 && hasTicket);   // true   둘 다 참
console.log(age >= 19 || hasTicket);   // true   하나라도 참
console.log(!hasTicket);               // false  뒤집기


// ---------------------------------------------------------------
// 4. 참/거짓으로 취급되는 값 (truthy / falsy)
// ---------------------------------------------------------------

// 아래 6개는 false 처럼 취급됩니다. (falsy)
//   false, 0, "" (빈 문자열), null, undefined, NaN
// 나머지는 전부 true 처럼 취급됩니다. (truthy)
//   "0", "false", [], {} 도 전부 truthy 입니다. 주의!

const inputValue = "";

if (inputValue) {
  console.log("입력됨");
} else {
  console.log("비어 있음");   // 이쪽이 실행됨
}

// [파이썬과 다른 점] 파이썬은 빈 리스트 [] 가 False 지만,
//                   자바스크립트의 빈 배열 [] 는 true 입니다.
if ([]) {
  console.log("JS에서 빈 배열은 true 입니다");
}


// ---------------------------------------------------------------
// 5. if / else if / else
// ---------------------------------------------------------------

// 파이썬의 elif 가 else if 로 바뀌고, 조건에 소괄호 ( ) 가 붙고,
// 콜론(:) 대신 중괄호 { } 를 씁니다.

const score = 85;

if (score >= 90) {
  console.log("A 학점");
} else if (score >= 80) {
  console.log("B 학점");        // 이쪽이 실행됨
} else if (score >= 70) {
  console.log("C 학점");
} else {
  console.log("F 학점");
}


// 중괄호는 문장이 한 줄이면 생략할 수 있지만, 항상 쓰는 것을 권합니다.
// 나중에 줄을 추가할 때 버그가 생기기 쉽습니다.


// ---------------------------------------------------------------
// 6. 삼항 연산자 - 한 줄 if
// ---------------------------------------------------------------

// 형태:  조건 ? 참일때값 : 거짓일때값
// 파이썬의  "성인" if age >= 19 else "미성년"  에 해당합니다.

const status = age >= 19 ? "성인" : "미성년자";
console.log(status);   // 성인

// 실무에서 매우 자주 보입니다. 화면에 값을 뿌릴 때 특히 많이 씁니다.
console.log(`${age}세는 ${age >= 19 ? "입장 가능" : "입장 불가"}`);


// ---------------------------------------------------------------
// 7. switch - 값이 딱 떨어질 때
// ---------------------------------------------------------------

const day = "수";

switch (day) {
  case "월":
  case "화":
  case "수":
  case "목":
  case "금":
    console.log("평일입니다");
    break;              // break 를 빼먹으면 아래 case 까지 실행됩니다!
  case "토":
  case "일":
    console.log("주말입니다");
    break;
  default:
    console.log("잘못된 입력");
}


// ---------------------------------------------------------------
// 8. 유용한 최신 문법 2가지
// ---------------------------------------------------------------

// (1) ?? (널 병합 연산자) - 값이 null/undefined 일 때만 기본값 사용
const userName = null;
console.log(userName ?? "손님");   // 손님

// (2) ?. (옵셔널 체이닝) - 없는 값을 파고들어도 에러 대신 undefined
const user = { name: "홍길동" };
console.log(user.address?.city);   // undefined (에러 안 남)
// console.log(user.address.city); // TypeError! 이건 에러가 납니다


