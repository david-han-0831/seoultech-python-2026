"""
2일차 - 03. 반복문 while

for 가 '몇 번 할지 정해졌을 때'라면
while 은 '조건이 참인 동안 계속' 반복합니다.
몇 번 돌지 미리 알 수 없을 때 씁니다.
"""

# ---------------------------------------------------------------
# 1. 기본 구조
# ---------------------------------------------------------------

count = 1                 # ① 시작값 준비
while count <= 5:         # ② 조건 검사
    print(count, end=" ")
    count += 1            # ③ 값 변경 ← 이걸 빠뜨리면 무한 루프!
print()

# [주의] 무한 루프가 걸리면 터미널에서 Ctrl + C 로 강제 종료합니다.
# 아래 코드는 절대 끝나지 않습니다. (실행하지 마세요)
#   i = 0
#   while i < 5:
#       print(i)      ← i 를 늘리지 않아 조건이 영원히 참


# ---------------------------------------------------------------
# 2. for 로 바꿔 쓸 수 있는 경우 / 없는 경우
# ---------------------------------------------------------------

# 횟수가 정해져 있으면 for 가 더 깔끔합니다.
for i in range(1, 6):
    print(i, end=" ")
print()

# 언제 끝날지 모를 때는 while 이어야 합니다.
# 예) 사용자가 올바른 값을 넣을 때까지 계속 물어보기
while True:
    answer = input("숫자를 입력하세요: ").strip()
    if answer.isdigit():
        number = int(answer)
        break                        # 조건을 만족하면 빠져나감
    print("숫자가 아닙니다. 다시 입력해 주세요.")

print(f"입력한 값: {number}")


# ---------------------------------------------------------------
# 3. while True + break : 메뉴 프로그램의 기본 뼈대
# ---------------------------------------------------------------

while True:
    print("\n1. 인사   2. 계산   0. 종료")
    choice = input("선택: ").strip()

    if choice == "1":
        print("안녕하세요!")
    elif choice == "2":
        a, b = map(int, input("두 수: ").split())
        print(f"합: {a + b}")
    elif choice == "0":
        print("종료합니다.")
        break
    else:
        print("잘못된 선택입니다.")


# ---------------------------------------------------------------
# 4. continue - 이번 회차 건너뛰기
# ---------------------------------------------------------------

i = 0
while i < 10:
    i += 1                # continue 앞에서 값을 바꿔야 합니다!
    if i % 2 == 0:
        continue          # 짝수면 아래를 건너뜀
    print(i, end=" ")     # 1 3 5 7 9
print()

# [흔한 실수] i += 1 을 continue 뒤에 두면 무한 루프가 됩니다.
#   while i < 10:
#       if i % 2 == 0:
#           continue      ← 여기서 계속 돌아가서 i 가 영원히 그대로
#       i += 1


# ---------------------------------------------------------------
# 5. 누적과 조건 종료
# ---------------------------------------------------------------

# 5-1. 합이 100을 넘는 순간 멈추기
total = 0
n = 1
while total <= 100:
    total += n
    n += 1
print(f"1부터 {n - 1}까지 더하면 {total} (100 초과)")

# 5-2. 자릿수 세기
number = 48213
digits = 0
temp = number
while temp > 0:
    temp //= 10       # 10으로 나눈 몫 (한 자리씩 지워짐)
    digits += 1
print(f"{number}는 {digits}자리 수입니다.")

# 5-3. 각 자리 숫자의 합
number = 48213
total = 0
temp = number
while temp > 0:
    total += temp % 10   # 마지막 자리
    temp //= 10
print(f"{number}의 자릿수 합: {total}")


# ---------------------------------------------------------------
# 6. 실전 예제 - 입력값 누적하기
# ---------------------------------------------------------------

print("\n숫자를 계속 입력하세요. (0을 입력하면 종료)")

numbers = []
while True:
    value = int(input("> "))
    if value == 0:
        break
    numbers.append(value)

if numbers:
    print(f"입력 개수 : {len(numbers)}")
    print(f"합계     : {sum(numbers)}")
    print(f"평균     : {sum(numbers) / len(numbers):.2f}")
    print(f"최댓값   : {max(numbers)}")
    print(f"최솟값   : {min(numbers)}")
else:
    print("입력된 숫자가 없습니다.")


