"""
2일차 - 02. 반복문 for

같은 일을 여러 번 시킬 때 씁니다.
'몇 번 할지 정해져 있을 때' 또는 '목록을 하나씩 훑을 때' for 를 씁니다.
"""

# ---------------------------------------------------------------
# 1. range() - 정해진 횟수만큼 반복
# ---------------------------------------------------------------

# range(끝) : 0부터 끝 '앞'까지
for i in range(5):
    print(i, end=" ")   # 0 1 2 3 4
print()

# range(시작, 끝)
for i in range(1, 6):
    print(i, end=" ")   # 1 2 3 4 5
print()

# range(시작, 끝, 간격)
for i in range(0, 11, 2):
    print(i, end=" ")   # 0 2 4 6 8 10
print()

# 거꾸로 (간격을 음수로)
for i in range(5, 0, -1):
    print(i, end=" ")   # 5 4 3 2 1
print()

# 값이 필요 없고 횟수만 필요하면 변수 이름을 _ 로 씁니다.
for _ in range(3):
    print("반복")


# ---------------------------------------------------------------
# 2. 목록을 하나씩 꺼내기
# ---------------------------------------------------------------

fruits = ["사과", "바나나", "포도"]

for fruit in fruits:
    print(f"저는 {fruit}를 좋아합니다.")

# 문자열도 하나씩 꺼낼 수 있습니다.
for char in "Python":
    print(char, end="-")
print()

# 딕셔너리
scores = {"국어": 90, "영어": 85, "수학": 77}
for subject, score in scores.items():
    print(f"{subject}: {score}점")


# ---------------------------------------------------------------
# 3. enumerate - 순번과 값을 함께
# ---------------------------------------------------------------

menu = ["아메리카노", "카페라떼", "녹차"]

for i, item in enumerate(menu, start=1):
    print(f"{i}. {item}")

# enumerate 를 안 쓰면 이렇게 해야 합니다. (덜 깔끔합니다)
for i in range(len(menu)):
    print(f"{i + 1}. {menu[i]}")


# ---------------------------------------------------------------
# 4. zip - 두 목록을 나란히
# ---------------------------------------------------------------

names = ["김철수", "이영희", "박민수"]
scores = [90, 85, 77]

for name, score in zip(names, scores):
    print(f"{name}: {score}점")

# 길이가 다르면 짧은 쪽에 맞춰 멈춥니다.
for a, b in zip([1, 2, 3], ["a", "b"]):
    print(a, b)   # (1,a) (2,b) 까지만


# ---------------------------------------------------------------
# 5. break 와 continue
# ---------------------------------------------------------------

# break : 반복을 즉시 끝냅니다
for i in range(1, 11):
    if i == 5:
        break
    print(i, end=" ")   # 1 2 3 4
print()

# continue : 이번 회차만 건너뛰고 다음으로 갑니다
for i in range(1, 11):
    if i % 2 == 0:
        continue
    print(i, end=" ")   # 1 3 5 7 9  (홀수만)
print()

# 실전: 목록에서 찾으면 바로 멈추기
students = ["김철수", "이영희", "박민수"]
target = "이영희"

for s in students:
    if s == target:
        print(f"{target}을(를) 찾았습니다.")
        break
else:
    # for 에 붙는 else 는 'break 없이 끝까지 돌았을 때'만 실행됩니다.
    print(f"{target}을(를) 찾지 못했습니다.")


# ---------------------------------------------------------------
# 6. 누적 - 반복문의 핵심 패턴
# ---------------------------------------------------------------

# 6-1. 합계
total = 0                    # 담을 그릇을 먼저 0으로 준비
for i in range(1, 101):
    total += i               # 하나씩 더해 나감
print(f"1~100 합계: {total}")

# 6-2. 곱셈 누적 (팩토리얼) - 그릇을 1로 시작해야 합니다
result = 1
for i in range(1, 6):
    result *= i
print(f"5! = {result}")      # 120

# 6-3. 개수 세기
scores = [88, 95, 70, 100, 62, 45, 91]
pass_count = 0
for s in scores:
    if s >= 80:
        pass_count += 1
print(f"80점 이상: {pass_count}명")

# 6-4. 새 리스트 만들기
squares = []
for i in range(1, 6):
    squares.append(i ** 2)
print(squares)   # [1, 4, 9, 16, 25]


# ---------------------------------------------------------------
# 7. 리스트 컴프리헨션 - 위 6-4 를 한 줄로
# ---------------------------------------------------------------

squares = [i ** 2 for i in range(1, 6)]
print(squares)

# 조건을 붙일 수도 있습니다.
evens = [i for i in range(1, 11) if i % 2 == 0]
print(evens)   # [2, 4, 6, 8, 10]

# 문자열 목록 가공
names = ["kim", "lee", "park"]
upper_names = [n.upper() for n in names]
print(upper_names)

