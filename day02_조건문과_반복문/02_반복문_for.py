# 8-1. 구구단 한 단
dan = 7
print(f"\n[{dan}단]")
for i in range(1, 10):
    print(f"{dan} x {i} = {dan * i}")

# 8-2. 별 찍기
print()
for i in range(1, 6):
    print("*" * i)

# 8-3. 1부터 100까지 3의 배수의 합
total = 0
for i in range(3, 101, 3):
    total += i
print(f"\n3의 배수 합계: {total}")

# 8-4. 소수(prime) 찾기
print("\n[2~30 사이의 소수]")
for n in range(2, 31):
    is_prime = True
    for d in range(2, n):
        if n % d == 0:
            is_prime = False
            break
    if is_prime:
        print(n, end=" ")
print()


