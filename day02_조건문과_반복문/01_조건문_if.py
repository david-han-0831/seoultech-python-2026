# ---------------------------------------------------------------
# 7. 한 줄 조건문 (삼항 연산자)
# ---------------------------------------------------------------

score = 80

# 일반적인 방법
if score >= 60:
    result = "합격"
else:
    result = "불합격"

# 한 줄로 줄이기 :  [참일 때 값] if [조건] else [거짓일 때 값]
result = "합격" if score >= 60 else "불합격"
print(result)

# f-string 안에서도 쓸 수 있습니다.
print(f"결과: {'합격' if score >= 60 else '불합격'}")


# ---------------------------------------------------------------
# 8. match 문 (파이썬 3.10 이상)
# ---------------------------------------------------------------

menu = "2"

match menu:
    case "1":
        print("아메리카노")
    case "2":
        print("카페라떼")
    case "3":
        print("녹차")
    case _:            # _ 는 '나머지 전부'
        print("없는 메뉴입니다.")


