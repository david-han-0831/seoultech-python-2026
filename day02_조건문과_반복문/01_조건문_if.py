# 9-1. 윤년 판별
year = 2026
if (year % 4 == 0 and year % 100 != 0) or year % 400 == 0:
    print(f"{year}년은 윤년입니다.")
else:
    print(f"{year}년은 평년입니다.")

# 9-2. BMI 계산과 판정
weight = 68.0   # kg
height = 1.75   # m
bmi = weight / (height ** 2)

if bmi < 18.5:
    status = "저체중"
elif bmi < 23:
    status = "정상"
elif bmi < 25:
    status = "과체중"
else:
    status = "비만"

print(f"BMI {bmi:.1f} → {status}")

# 9-3. 주차 요금 계산 (30분 무료, 이후 10분당 500원)
minutes = 95
if minutes <= 30:
    fee = 0
else:
    over = minutes - 30
    # 올림 계산: 남은 시간을 10분 단위로 올려서 셉니다
    units = (over + 9) // 10
    fee = units * 500
print(f"{minutes}분 주차 요금: {fee:,}원")


