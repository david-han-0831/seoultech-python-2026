# ---------------------------------------------------------------
# 1. 가장 기본
# ---------------------------------------------------------------

age = 20

if age >= 19:
    print("성인입니다.")     # ← 앞에 공백 4칸(들여쓰기)이 있어야 합니다!

print("여기는 조건과 상관없이 항상 실행됩니다.")

# [중요] 파이썬은 중괄호 { } 대신 '들여쓰기'로 코드 묶음을 구분합니다.
#        들여쓰기는 공백 4칸이 표준입니다. 탭과 공백을 섞으면 에러가 납니다.


# ---------------------------------------------------------------
# 2. if - else : 둘 중 하나
# ---------------------------------------------------------------

score = 75

if score >= 60:
    print("합격")
else:
    print("불합격")


# ---------------------------------------------------------------
# 3. if - elif - else : 여러 갈래
# ---------------------------------------------------------------

score = 85

if score >= 90:
    grade = "A"
elif score >= 80:      # 위 조건이 거짓일 때만 검사합니다
    grade = "B"
elif score >= 70:
    grade = "C"
elif score >= 60:
    grade = "D"
else:
    grade = "F"

print(f"{score}점은 {grade}학점입니다.")

# [주의] 순서가 중요합니다. 아래처럼 쓰면 95점도 D가 나옵니다.
#   if score >= 60:  ... elif score >= 90: ...
#   → 위에서부터 검사하다 처음 참인 곳에서 멈추기 때문입니다.


# ---------------------------------------------------------------
# 4. 조건 조합 - and / or / not
